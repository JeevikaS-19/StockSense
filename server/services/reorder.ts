import type { Db, Row } from '../db.ts';
import { withTransaction } from '../db.ts';
import { fail, round2, toNumber } from '../errors.ts';
import { writeAudit } from './audit.ts';
import { notifyAdmins } from './notifications.ts';
import { OPEN_STATUS_SQL, addLines, createPurchaseOrderRow, openDraftForSupplier } from './purchaseOrders.ts';

// Outstanding quantity on open purchase orders for product p (table alias p). Used everywhere "on order" is shown.
export const ON_ORDER_SQL = `COALESCE((
  SELECT SUM(i.qty_ordered - i.qty_received - i.qty_rejected)
  FROM purchase_order_items i JOIN purchase_orders po ON po.id = i.po_id
  WHERE i.product_id = p.id AND po.status IN ${OPEN_STATUS_SQL}), 0)`;

export interface ScanSummary {
  automation_mode: string;
  created_pos: number;
  updated_pos: number;
  items_added: number;
  below_reorder: number;
  needs_supplier: { id: number; sku: string; name: string }[];
  added: { product_id: number; sku: string; quantity: number; po_number: string }[];
}

// Reorder overview for one lab. "Below reorder point" uses on-hand stock; the order trigger uses effective
// stock (on-hand plus open orders). Both are returned so the UI can explain any difference.
export async function reorderOverview(db: Db, labId: number): Promise<Row[]> {
  const res = await db.query(
    `SELECT p.id, p.sku, p.name, p.unit, p.category, p.quantity, p.reorder_level, p.reorder_qty,
            p.lead_time_days, p.unit_price, p.supplier_id, s.name AS supplier_name,
            ${ON_ORDER_SQL} AS on_order
     FROM products p LEFT JOIN suppliers s ON s.id = p.supplier_id
     WHERE p.lab_id = $1 AND p.is_active = true
     ORDER BY p.name`,
    [labId]
  );
  return res.rows.map((row) => {
    const quantity = toNumber(row.quantity);
    const reorderLevel = toNumber(row.reorder_level);
    const onOrder = round2(toNumber(row.on_order));
    const effective = round2(quantity + onOrder);
    return {
      id: Number(row.id),
      sku: row.sku,
      name: row.name,
      unit: row.unit,
      category: row.category,
      quantity,
      on_order: onOrder,
      effective_stock: effective,
      reorder_level: reorderLevel,
      reorder_qty: row.reorder_qty === null ? null : Number(row.reorder_qty),
      lead_time_days: Number(row.lead_time_days),
      unit_price: toNumber(row.unit_price),
      supplier_id: row.supplier_id === null ? null : Number(row.supplier_id),
      supplier_name: row.supplier_name ?? null,
      below_reorder_point: quantity <= reorderLevel,
      out_of_stock: quantity === 0,
      needs_supplier: effective <= reorderLevel && row.supplier_id === null,
      suggested_order_qty: row.reorder_qty !== null ? Number(row.reorder_qty) : Math.max(reorderLevel * 2 - effective, 1),
    };
  });
}

// Implements the reorder rules for one lab (Prompt 2). Products whose effective stock is at or below the
// reorder point are added to the lab's open draft PO for their supplier, creating one if needed.
// Because the new line counts toward effective stock, a product is never added twice.
export async function scanLabForReorders(tx: Db, labId: number, actorId: number | null): Promise<ScanSummary> {
  const labRes = await tx.query<{ automation_mode: string }>('SELECT automation_mode FROM labs WHERE id = $1', [labId]);
  if (labRes.rows.length === 0) fail(404, 'NOT_FOUND', 'Laboratory not found.');
  const mode = labRes.rows[0].automation_mode;

  // FOR UPDATE serialises concurrent scans of the same lab.
  const products = await tx.query(
    `SELECT p.id, p.sku, p.name, p.quantity, p.reorder_level, p.reorder_qty, p.unit_price, p.supplier_id,
            ${ON_ORDER_SQL} AS on_order
     FROM products p WHERE p.lab_id = $1 AND p.is_active = true
     ORDER BY p.id FOR UPDATE OF p`,
    [labId]
  );

  const summary: ScanSummary = {
    automation_mode: mode,
    created_pos: 0,
    updated_pos: 0,
    items_added: 0,
    below_reorder: 0,
    needs_supplier: [],
    added: [],
  };
  const touchedExisting = new Set<number>();

  for (const p of products.rows) {
    const quantity = toNumber(p.quantity);
    const reorderLevel = toNumber(p.reorder_level);
    if (quantity <= reorderLevel) summary.below_reorder++;

    const effective = round2(quantity + toNumber(p.on_order));
    if (effective > reorderLevel) continue;

    if (p.supplier_id === null) {
      summary.needs_supplier.push({ id: Number(p.id), sku: p.sku, name: p.name });
      continue;
    }
    if (mode === 'alert_only') continue;

    const supplierId = Number(p.supplier_id);
    let draft = await openDraftForSupplier(tx, labId, supplierId);
    if (!draft) {
      draft = await createPurchaseOrderRow(tx, { labId, supplierId, createdBy: null, source: 'auto', notes: 'Generated by reorder rules.' });
      summary.created_pos++;
    } else {
      touchedExisting.add(Number(draft.id));
    }

    const already = await tx.query('SELECT 1 FROM purchase_order_items WHERE po_id = $1 AND product_id = $2', [draft.id, p.id]);
    if (already.rows.length > 0) continue;

    const orderQty = p.reorder_qty !== null ? Number(p.reorder_qty) : Math.max(reorderLevel * 2 - effective, 1);
    await addLines(tx, draft, [{ product_id: Number(p.id), quantity: orderQty, unit_price: toNumber(p.unit_price) }], actorId);
    summary.items_added++;
    summary.added.push({ product_id: Number(p.id), sku: p.sku, quantity: orderQty, po_number: draft.po_number });
  }

  summary.updated_pos = touchedExisting.size;

  await writeAudit(tx, {
    actorId,
    action: 'reorder.scan',
    entityType: 'lab',
    entityId: labId,
    labId,
    newValue: { created_pos: summary.created_pos, updated_pos: summary.updated_pos, items_added: summary.items_added },
  });

  if (mode !== 'alert_only' && (summary.created_pos > 0 || summary.items_added > 0)) {
    await notifyAdmins(tx, {
      labId,
      type: 'reorder_drafts',
      title: `Reorder rules added ${summary.items_added} item${summary.items_added === 1 ? '' : 's'} to draft POs`,
      body: `${summary.created_pos} new draft PO${summary.created_pos === 1 ? '' : 's'} created.`,
      link: '/purchase-orders?status=draft',
    });
  }
  return summary;
}

export function runReorderScan(labId: number, actorId: number | null): Promise<ScanSummary> {
  return withTransaction((tx) => scanLabForReorders(tx, labId, actorId));
}

export interface ReorderFieldsInput {
  reorder_level?: number;
  reorder_qty?: number | null;
  lead_time_days?: number;
}

// Inline edit of the three reorder fields. Each changed value is written to audit_log.
export async function updateReorderFields(tx: Db, productId: number, labId: number, input: ReorderFieldsInput, actorId: number): Promise<void> {
  const current = await tx.query(
    'SELECT reorder_level, reorder_qty, lead_time_days FROM products WHERE id = $1 AND lab_id = $2 AND is_active = true FOR UPDATE',
    [productId, labId]
  );
  if (current.rows.length === 0) fail(404, 'NOT_FOUND', 'Product not found in this laboratory.');
  const before = current.rows[0];

  const next = {
    reorder_level: input.reorder_level ?? toNumber(before.reorder_level),
    reorder_qty: input.reorder_qty === undefined ? before.reorder_qty : input.reorder_qty,
    lead_time_days: input.lead_time_days ?? Number(before.lead_time_days),
  };

  await tx.query(
    `UPDATE products SET reorder_level = $1, reorder_qty = $2, lead_time_days = $3, updated_at = NOW()
     WHERE id = $4 AND lab_id = $5`,
    [next.reorder_level, next.reorder_qty, next.lead_time_days, productId, labId]
  );

  for (const field of ['reorder_level', 'reorder_qty', 'lead_time_days'] as const) {
    const oldValue = before[field] === null ? null : Number(before[field]);
    const newValue = next[field] === null ? null : Number(next[field]);
    if (oldValue !== newValue) {
      await writeAudit(tx, {
        actorId,
        action: `product.${field}`,
        entityType: 'product',
        entityId: productId,
        labId,
        oldValue,
        newValue,
      });
    }
  }
}
